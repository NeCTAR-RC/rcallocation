from rcallocation.extensions import db
from rcallocation.models import base
from rcallocation.models import reference


class Organisation(db.Model):
    """This represents an Organisation related to a project and / or
    its researchers.  Where possible, we will use organisation that
    has a Research Organization Registry (ROR) id and record, and we
    will treat that as a source of truth.  However, there many examples
    of organisations that don't have ROR ids.  We cater for these by
    allowing the user to type in a new organisation, subject to vetting
    by the approver who approves the allocation or amendment.

    Note that none of the fields is unique, so therefore we need to
    use an implicit autogenerated 'id' as the primary key.

    When populating from the ROR data dump, we will filter out records
    marked as inactive or withdrawn.
    """

    __tablename__ = "organisation"

    id = db.Column(db.Integer, primary_key=True)
    #: Blank for organisations that don't (yet) have an ROR id
    ror_id = db.Column(db.String(32), nullable=False, default="", index=True)
    #: The official full name, e.g. 'The University of Queensland'
    full_name = db.Column(db.String(200), nullable=False, index=True)
    #: Optional short name or acronym, e.g. 'UQ'
    short_name = db.Column(
        db.String(16), nullable=False, default="", index=True
    )
    #: Organisational website URL for disambiguation purposes
    url = db.Column(db.String(64), nullable=False, default="")
    #: Two character ISO 3166-1 country code
    country = db.Column(db.String(2), nullable=False, index=True)
    parent_id = db.Column(
        db.Integer,
        db.ForeignKey("organisation.id", ondelete="SET NULL"),
        nullable=True,
    )
    #: If false, this organisation should no longer be used
    enabled = db.Column(db.Boolean, nullable=False, default=True)
    #: Keystone id of the person who proposed this ('type in') organisation
    proposed_by = db.Column(db.String(64), nullable=False, default="")
    #: The approver who vetted this (non ROR) organisation record
    vetted_by_id = db.Column(
        db.Integer, db.ForeignKey("approver.id"), nullable=True
    )

    parent = db.relationship(
        "Organisation",
        remote_side=[id],
        foreign_keys=[parent_id],
        backref=db.backref("children", lazy="select"),
    )
    #: Organisations this one was preceded by (reverse: ``supersedes``)
    precedes = db.relationship(
        "Organisation",
        secondary=base.organisation_precedes,
        primaryjoin=id == base.organisation_precedes.c.from_organisation_id,
        secondaryjoin=id == base.organisation_precedes.c.to_organisation_id,
        backref=db.backref("supersedes", lazy="select"),
        lazy="selectin",
        join_depth=1,
    )
    vetted_by = db.relationship(reference.Approver, lazy="joined")

    __table_args__ = (
        db.UniqueConstraint(
            "full_name", "ror_id", "url", name="unique_organisation"
        ),
    )

    @property
    def vetted(self):
        return bool(self.ror_id) or self.vetted_by_id is not None

    def __repr__(self):
        return f"<Organisation {self.id} {self.full_name}>"
